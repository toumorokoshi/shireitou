/// Generates `lib/src/theme/generated/themes.g.dart` from
/// `themes/manifest.yaml` (AV-097). With `fetch`, first downloads the
/// manifest's tinted-theming schemes into `themes/vendor/`.
///
/// Run from `app/`: `dart run tool/gen_themes.dart [fetch]`, or
/// `just themes` and `just fetch-themes`.
library;

import 'dart:io';

import 'package:yaml/yaml.dart';

const _manifest = 'themes/manifest.yaml';
const _vendor = 'themes/vendor';
const _output = 'lib/src/theme/generated/themes.g.dart';
const _schemesUrl = 'https://raw.githubusercontent.com/tinted-theming/schemes';

Future<void> main(List<String> args) async {
  final manifest = loadYaml(File(_manifest).readAsStringSync()) as YamlMap;
  final themes = (manifest['themes'] as YamlMap).map(
    (id, entry) => MapEntry(id as String, entry as YamlMap),
  );
  if (args.contains('fetch')) {
    await _fetch(manifest['tinted_commit'] as String, themes.values);
  }
  File(_output).writeAsStringSync(generate(themes, _read));
  stdout.writeln('wrote $_output (${themes.length} themes)');
}

/// The scheme file of a manifest [entry], relative to `themes/`.
String schemePath(YamlMap entry) =>
    entry['file'] as String? ?? 'vendor/${entry['scheme']}.yaml';

YamlMap _read(String path) =>
    loadYaml(File('themes/$path').readAsStringSync()) as YamlMap;

Future<void> _fetch(String commit, Iterable<YamlMap> entries) async {
  final client = HttpClient();
  try {
    Future<void> download(String from, String to) async {
      final request = await client.getUrl(
        Uri.parse('$_schemesUrl/$commit/$from'),
      );
      final response = await request.close();
      if (response.statusCode != 200) {
        throw HttpException('${response.statusCode} for $from');
      }
      final file = File(to)..createSync(recursive: true);
      await response.pipe(file.openWrite());
    }

    await download('LICENSE', '$_vendor/LICENSE');
    for (final entry in entries) {
      if (entry['scheme'] case final String scheme) {
        await download('$scheme.yaml', '$_vendor/$scheme.yaml');
      }
    }
  } finally {
    client.close();
  }
}

/// The Base24 keys, `base00` to `base17`.
final _keys = [
  for (var i = 0; i < 24; i++) 'base${i.toRadixString(16).padLeft(2, '0')}',
];

/// What a Base16 scheme's missing Base24 colours fall back to (the Base24
/// spec): the darker backgrounds to `base00`, the bright colours to the
/// normal ones.
const _base16Fallback = {
  'base10': 'base00',
  'base11': 'base00',
  'base12': 'base08',
  'base13': 'base0a',
  'base14': 'base0b',
  'base15': 'base0c',
  'base16': 'base0d',
  'base17': 'base0e',
};

/// The 24 ARGB colours of a scheme's [palette], case-insensitive keys and
/// values with or without `#`.
List<int> base24Colors(YamlMap palette) {
  final byKey = {
    for (final MapEntry(:key, :value) in palette.entries)
      (key as String).toLowerCase(): value as String,
  };
  int color(String key) {
    final hex = byKey[key] ?? byKey[_base16Fallback[key]];
    if (hex == null) throw FormatException('no $key');
    return 0xFF000000 | int.parse(hex.replaceFirst('#', ''), radix: 16);
  }

  return [for (final key in _keys) color(key)];
}

/// The Dart source for [themes] (id to manifest entry), reading each
/// scheme with [read].
String generate(
  Map<String, YamlMap> themes,
  YamlMap Function(String path) read,
) {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_themes.dart from themes/manifest.yaml.')
    ..writeln('// Do not edit; run `just themes`.')
    ..writeln()
    ..writeln("import 'package:flutter/material.dart';")
    ..writeln()
    ..writeln("import '../theme_spec.dart';")
    ..writeln()
    ..writeln('/// Every theme, in the manifest\'s order.')
    ..writeln('const generatedThemes = <ThemeSpec>[');
  for (final MapEntry(key: id, value: entry) in themes.entries) {
    final scheme = read(schemePath(entry));
    final name = entry['name'] as String? ?? scheme['name'] as String;
    final dark = switch (scheme['variant']) {
      'dark' => true,
      'light' => false,
      final other => throw FormatException('$id: variant $other'),
    };
    final colors = base24Colors(scheme['palette'] as YamlMap)
        .map((c) => '0x${c.toRadixString(16).toUpperCase()}')
        .join(', ');
    out
      ..writeln('  ThemeSpec(')
      ..writeln("    id: '$id',")
      ..writeln("    name: '${name.replaceAll("'", r"\'")}',")
      ..writeln('    brightness: Brightness.${dark ? 'dark' : 'light'},')
      ..writeln('    colors: [$colors],')
      ..writeln('  ),');
  }
  out.writeln('];');
  return out.toString();
}
